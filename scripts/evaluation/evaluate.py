#!/usr/bin/env python3
"""
Evaluate the RAG chatbot against a QA dataset generated by generate_dataset.py.

For every question the script:
  1. Sends it to the RAG API  (/api/chat)
  2. Asks the LLM to judge the answer on a 1-5 scale (LLM-as-judge)
  3. Checks whether the correct source file appeared in the retrieved chunks

Outputs:
  - Live progress to stdout
  - Full results JSONL   (--results-jsonl)
  - Human-readable report to stdout

Metrics reported:
  score_mean / score_p50        — answer quality  (1-5)
  retrieval_hit_rate            — correct source found in top-k chunks
  cache_hit_rate                — how many answers came from Redis cache
  no_info_rate                  — how often the model said "I don't know"
  avg_latency_ms                — end-to-end wall time per request

Usage:
    python scripts/evaluation/evaluate.py \\
        --dataset data/eval_dataset.jsonl \\
        --api-url http://localhost:8010 \\
        --llm-url http://localhost:8001/v1 \\
        --results-jsonl data/eval_results.jsonl

    # Only evaluate one course
    python scripts/evaluation/evaluate.py \\
        --dataset data/eval_dataset.jsonl \\
        --course-id FILOS-2026 \\
        --api-url http://localhost:8010 \\
        --llm-url http://localhost:8001/v1

    # Compare two result files
    python scripts/evaluation/evaluate.py --compare before.jsonl after.jsonl
"""

import argparse
import asyncio
import json
import statistics
import sys
import time
from pathlib import Path
from typing import Dict, List, Optional

import httpx

# ---------------------------------------------------------------------------
# LLM-as-judge prompt
# ---------------------------------------------------------------------------
JUDGE_PROMPT = """Ești un evaluator obiectiv. Compară răspunsul unui asistent AI cu răspunsul corect.

ÎNTREBARE:
{question}

RĂSPUNS CORECT (gold):
{gold_answer}

RĂSPUNS GENERAT DE AI:
{rag_answer}

Evaluează răspunsul AI pe o scală de la 1 la 5:
1 — Complet greșit sau irelevant
2 — Parțial corect, lipsesc informații importante
3 — Corect în mare parte, dar incomplet sau cu mici erori
4 — Corect și complet, cu mici imperfecțiuni
5 — Perfect: corect, complet, bine structurat

Returnează DOAR JSON valid (fără explicații):
{{"score": <1-5>, "reason": "<1-2 propoziții scurte>"}}

JSON:"""

NO_INFO_PHRASES = [
    "не нашел", "не найдено", "нет информации", "nu am găsit",
    "nu există", "I didn't find", "not found", "no information",
    "материалах курса нет", "nu se regăsește",
]


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def percentile(data: List[float], p: int) -> float:
    if not data:
        return 0.0
    s = sorted(data)
    k = (len(s) - 1) * p / 100
    lo, hi = int(k), min(int(k) + 1, len(s) - 1)
    return s[lo] + (s[hi] - s[lo]) * (k - lo)


def is_no_info(answer: str) -> bool:
    lower = answer.lower()
    return any(phrase in lower for phrase in NO_INFO_PHRASES)


# ---------------------------------------------------------------------------
# API calls
# ---------------------------------------------------------------------------
async def call_rag(
    client: httpx.AsyncClient,
    api_url: str,
    question: str,
    course_id: Optional[str],
) -> Dict:
    payload = {"question": question, "language": "ro"}
    if course_id:
        payload["course_id"] = course_id

    t0 = time.perf_counter()
    try:
        resp = await client.post(f"{api_url}/api/chat", json=payload, timeout=120)
        wall_ms = (time.perf_counter() - t0) * 1000
        resp.raise_for_status()
        data = resp.json()
        return {
            "ok": True,
            "answer": data.get("answer", ""),
            "cached": data.get("cached", False),
            "sources": data.get("sources", []),
            "timing": data.get("timing"),
            "wall_ms": wall_ms,
        }
    except Exception as e:
        wall_ms = (time.perf_counter() - t0) * 1000
        return {"ok": False, "error": str(e), "wall_ms": wall_ms, "answer": "", "sources": [], "cached": False}


async def call_judge(
    client: httpx.AsyncClient,
    llm_url: str,
    model: str,
    question: str,
    gold_answer: str,
    rag_answer: str,
) -> Dict:
    prompt = JUDGE_PROMPT.format(question=question, gold_answer=gold_answer, rag_answer=rag_answer)
    try:
        resp = await client.post(
            f"{llm_url}/chat/completions",
            json={
                "model": model,
                "messages": [{"role": "user", "content": prompt}],
                "max_tokens": 200,
                "temperature": 0.0,
            },
            timeout=60,
        )
        resp.raise_for_status()
        raw = resp.json()["choices"][0]["message"]["content"].strip()
        start = raw.find("{")
        end = raw.rfind("}") + 1
        if start >= 0 and end > start:
            parsed = json.loads(raw[start:end])
            return {"score": int(parsed.get("score", 0)), "reason": parsed.get("reason", "")}
    except Exception as e:
        pass
    return {"score": 0, "reason": "judge_error"}


def retrieval_hit(sources: List[Dict], expected_file: str) -> bool:
    """True if expected_file appears in the retrieved source list."""
    stem = Path(expected_file).stem.lower()
    for src in sources:
        topic = str(src.get("topic", "")).lower()
        document = str(src.get("document", "")).lower()
        if stem in topic or stem in document:
            return True
    return False


# ---------------------------------------------------------------------------
# Main evaluation loop
# ---------------------------------------------------------------------------
async def evaluate(
    dataset: List[Dict],
    api_url: str,
    llm_url: str,
    model: str,
    course_id_filter: Optional[str],
    concurrency: int,
    judge_url: Optional[str] = None,
    judge_model: Optional[str] = None,
) -> List[Dict]:
    if course_id_filter:
        dataset = [r for r in dataset if r["course_id"] == course_id_filter]

    print(f"Evaluating {len(dataset)} QA pairs  (concurrency={concurrency})")
    sem = asyncio.Semaphore(concurrency)
    results = []
    counter = {"n": 0}

    async def process_one(client: httpx.AsyncClient, item: Dict) -> Dict:
        async with sem:
            # Step 1: ask the RAG
            rag = await call_rag(client, api_url, item["question"], item.get("course_id"))

            # Step 2: judge
            judge = {"score": 0, "reason": "rag_error"}
            if rag["ok"] and rag["answer"]:
                judge = await call_judge(
                    client, judge_url or llm_url, judge_model or model,
                    item["question"], item["gold_answer"], rag["answer"]
                )

            # Step 3: retrieval hit
            hit = retrieval_hit(rag.get("sources", []), item.get("source_file", ""))

            result = {
                "id":             item["id"],
                "course_id":      item["course_id"],
                "source_file":    item.get("source_file", ""),
                "question":       item["question"],
                "gold_answer":    item["gold_answer"],
                "rag_answer":     rag.get("answer", ""),
                "score":          judge["score"],
                "judge_reason":   judge["reason"],
                "retrieval_hit":  hit,
                "cached":         rag.get("cached", False),
                "no_info":        is_no_info(rag.get("answer", "")),
                "wall_ms":        rag.get("wall_ms", 0),
                "timing":         rag.get("timing"),
                "rag_ok":         rag["ok"],
            }

            counter["n"] += 1
            n = counter["n"]
            total = len(dataset)
            score_str = str(judge["score"]) if rag["ok"] else "ERR"
            hit_str = "HIT" if hit else "mis"
            cached_str = "CACHE" if rag["cached"] else "LLM  "
            print(
                f"  [{n:3d}/{total}] score={score_str}  {hit_str}  {cached_str}"
                f"  {rag['wall_ms']:6.0f}ms  {item['question'][:55]}"
            )
            return result

    async with httpx.AsyncClient() as client:
        tasks = [asyncio.create_task(process_one(client, item)) for item in dataset]
        results = await asyncio.gather(*tasks)

    return list(results)


# ---------------------------------------------------------------------------
# Reporting
# ---------------------------------------------------------------------------
def print_report(results: List[Dict], label: str = "") -> None:
    ok = [r for r in results if r["rag_ok"]]
    if not ok:
        print("No successful results to report.")
        return

    scores        = [r["score"] for r in ok if r["score"] > 0]
    hits          = [r for r in ok if r["retrieval_hit"]]
    cached        = [r for r in ok if r["cached"]]
    no_info       = [r for r in ok if r["no_info"]]
    latencies     = [r["wall_ms"] for r in ok]

    header = f"  REPORT{' — ' + label if label else ''}"
    print(f"\n{'':=<70}")
    print(header)
    print(f"{'':=<70}")
    print(f"  Total evaluated:     {len(results)}")
    print(f"  Successful RAG calls:{len(ok)}")
    print(f"  Errors:              {len(results) - len(ok)}")
    print()

    if scores:
        print(f"  Answer quality (LLM-as-judge, 1-5):")
        print(f"    mean   = {statistics.mean(scores):.2f}")
        print(f"    p50    = {percentile(scores, 50):.1f}")
        print(f"    p25    = {percentile(scores, 25):.1f}")
        print(f"    p75    = {percentile(scores, 75):.1f}")
        dist = {i: scores.count(i) for i in range(1, 6)}
        bar = "  ".join(f"{k}★:{v}" for k, v in dist.items())
        print(f"    dist   = {bar}")

    print()
    print(f"  Retrieval hit rate:  {len(hits)}/{len(ok)} = {len(hits)/len(ok)*100:.1f}%")
    print(f"  Cache hit rate:      {len(cached)}/{len(ok)} = {len(cached)/len(ok)*100:.1f}%")
    print(f"  'No info' rate:      {len(no_info)}/{len(ok)} = {len(no_info)/len(ok)*100:.1f}%")
    print()
    print(f"  Latency (wall ms):")
    print(f"    p50={percentile(latencies,50):.0f}  p95={percentile(latencies,95):.0f}  mean={statistics.mean(latencies):.0f}")

    # Per-course breakdown
    courses = sorted({r["course_id"] for r in ok})
    if len(courses) > 1:
        print()
        print("  Per-course breakdown:")
        for cid in courses:
            cr = [r for r in ok if r["course_id"] == cid]
            cs = [r["score"] for r in cr if r["score"] > 0]
            ch = sum(1 for r in cr if r["retrieval_hit"])
            mean_s = f"{statistics.mean(cs):.2f}" if cs else "N/A"
            print(f"    {cid:20s}  n={len(cr):3d}  score={mean_s}  hit={ch}/{len(cr)}")

    # Worst answers (score ≤ 2)
    worst = sorted([r for r in ok if r["score"] in (1, 2)], key=lambda r: r["score"])
    if worst:
        print(f"\n  Worst answers (score 1-2, showing up to 5):")
        for r in worst[:5]:
            print(f"    [{r['score']}★] {r['question'][:70]}")
            print(f"          Reason: {r['judge_reason']}")

    print(f"{'':=<70}\n")


def compare_results(before_path: str, after_path: str) -> None:
    def load(p: str) -> List[Dict]:
        with open(p) as f:
            return [json.loads(line) for line in f if line.strip()]

    before = [r for r in load(before_path) if r.get("rag_ok")]
    after  = [r for r in load(after_path)  if r.get("rag_ok")]

    print(f"\n{'':=<70}")
    print(f"  COMPARISON")
    print(f"  BEFORE: {before_path}  ({len(before)} ok)")
    print(f"  AFTER:  {after_path}  ({len(after)} ok)")
    print(f"{'':=<70}")

    def mean_score(rs): return statistics.mean([r["score"] for r in rs if r["score"] > 0]) if rs else 0
    def hit_rate(rs):   return sum(1 for r in rs if r["retrieval_hit"]) / len(rs) if rs else 0
    def noinf_rate(rs): return sum(1 for r in rs if r["no_info"]) / len(rs) if rs else 0
    def p50_lat(rs):    return percentile([r["wall_ms"] for r in rs], 50)

    rows = [
        ("score (mean)",       f"{mean_score(before):.2f}", f"{mean_score(after):.2f}", True),
        ("retrieval hit rate", f"{hit_rate(before)*100:.1f}%", f"{hit_rate(after)*100:.1f}%", True),
        ("no-info rate",       f"{noinf_rate(before)*100:.1f}%", f"{noinf_rate(after)*100:.1f}%", False),
        ("latency p50 (ms)",   f"{p50_lat(before):.0f}", f"{p50_lat(after):.0f}", False),
    ]

    print(f"  {'metric':22s}  {'before':>10}  {'after':>10}  {'change':>10}")
    print(f"  {'-'*58}")
    for label, b_val, a_val, higher_better in rows:
        try:
            b_f = float(b_val.replace("%", ""))
            a_f = float(a_val.replace("%", ""))
            diff = a_f - b_f
            sign = "+" if diff > 0 else ""
            better = (diff > 0) == higher_better
            arrow = "↑" if better else ("↓" if not better and diff != 0 else "=")
            change = f"{sign}{diff:.1f} {arrow}"
        except ValueError:
            change = "—"
        print(f"  {label:22s}  {b_val:>10}  {a_val:>10}  {change:>10}")

    print(f"{'':=<70}\n")


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------
async def async_main(args: argparse.Namespace) -> None:
    if args.compare:
        compare_results(args.compare[0], args.compare[1])
        return

    dataset_path = Path(args.dataset)
    if not dataset_path.exists():
        print(f"Dataset not found: {dataset_path}")
        print("Run generate_dataset.py first.")
        sys.exit(1)

    with open(dataset_path, encoding="utf-8") as f:
        dataset = [json.loads(line) for line in f if line.strip()]

    print(f"Loaded {len(dataset)} items from {dataset_path}")

    # Auto-detect model
    async with httpx.AsyncClient() as probe:
        try:
            resp = await probe.get(f"{args.llm_url}/models", timeout=10)
            model = resp.json()["data"][0]["id"]
            print(f"Judge model: {model}")
        except Exception:
            model = args.model
            print(f"Judge model (fallback): {model}")

    judge_url = (args.judge_url or args.llm_url).rstrip("/")
    judge_model = args.judge_model or model

    if judge_url != args.llm_url.rstrip("/") or judge_model != model:
        print(f"Judge model: {judge_model} @ {judge_url}  (separate from answering model ✅)")
    else:
        print(f"⚠️  Judge == answering model ({model}) — results may be self-biased")

    results = await evaluate(
        dataset=dataset,
        api_url=args.api_url.rstrip("/"),
        llm_url=args.llm_url.rstrip("/"),
        model=model,
        course_id_filter=args.course_id,
        concurrency=args.concurrency,
        judge_url=judge_url,
        judge_model=judge_model,
    )

    print_report(results)

    if args.results_jsonl:
        out_path = Path(args.results_jsonl)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        with open(out_path, "w", encoding="utf-8") as f:
            for r in results:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
        print(f"Full results saved: {out_path}")
        print(f"(To compare later: --compare {out_path} results_after.jsonl)")


def main() -> None:
    parser = argparse.ArgumentParser(description="Evaluate RAG chatbot on a QA dataset")
    parser.add_argument("--dataset",       default="data/eval_dataset.jsonl",   help="JSONL dataset from generate_dataset.py")
    parser.add_argument("--api-url",       default="http://localhost:8010",      help="RAG API base URL")
    parser.add_argument("--llm-url",       default="http://localhost:8001/v1",   help="vLLM base URL (for LLM-as-judge)")
    parser.add_argument("--model",         default="Qwen/Qwen2.5-7B-Instruct",  help="Model name fallback")
    parser.add_argument("--course-id",     help="Evaluate only this course")
    parser.add_argument("--concurrency",   type=int, default=3,                  help="Parallel requests (default: 3)")
    parser.add_argument("--judge-url",     default=None,                         help="Separate vLLM URL for judge (avoids self-bias). Default: same as --llm-url")
    parser.add_argument("--judge-model",   default=None,                         help="Judge model name override")
    parser.add_argument("--results-jsonl", help="Save full results to JSONL file")
    parser.add_argument("--compare",       nargs=2, metavar=("BEFORE.jsonl", "AFTER.jsonl"),
                        help="Compare two result files")
    args = parser.parse_args()
    asyncio.run(async_main(args))


if __name__ == "__main__":
    main()
